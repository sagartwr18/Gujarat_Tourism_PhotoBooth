import { createClient } from '@supabase/supabase-js'
import dotenv from 'dotenv'

dotenv.config()

const SUPABASE_URL = (process.env.SUPABASE_URL || '').trim().replace(/\/+$/, '')
const SUPABASE_SERVICE_ROLE_KEY = (process.env.SUPABASE_SERVICE_ROLE_KEY || '').trim()

console.log('\n=============================================')
console.log('✦ VIBRANT GUJARAT • SUPABASE CONNECTION TEST')
console.log('=============================================\n')

if (!SUPABASE_URL || SUPABASE_URL.includes('your-project-ref')) {
  console.error('❌ ERROR: SUPABASE_URL is missing or still has placeholder value in .env')
  console.error('👉 Please set SUPABASE_URL in your .env file to your actual Supabase Project URL.')
  process.exitCode = 1
} else if (!SUPABASE_SERVICE_ROLE_KEY || SUPABASE_SERVICE_ROLE_KEY.includes('your_service_role_key')) {
  console.error('❌ ERROR: SUPABASE_SERVICE_ROLE_KEY is missing or still has placeholder value in .env')
  console.error('👉 Please set SUPABASE_SERVICE_ROLE_KEY in your .env file.')
  process.exitCode = 1
} else {
  console.log('✓ Supabase URL detected:', SUPABASE_URL)
  console.log('✓ Service Role Key detected (length:', SUPABASE_SERVICE_ROLE_KEY.length, 'chars)')

  const supabase = createClient(SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY)

  async function runTest() {
    try {
      console.log('\nStep 1: Checking if "emails" table and "background_name" column exist in Supabase...')
      const { data: existingRows, error: readError } = await supabase
        .from('emails')
        .select('id, email, email_frequency, background_name')
        .limit(5)

      if (readError) {
        if (readError.message?.includes('background_name')) {
          console.error('\n⚠️ "emails" table exists, but the "background_name" column is missing!')
          console.error('Message:', readError.message)
          console.log('\n👉 TO ADD THE COLUMN:')
          console.log('1. Go to your Supabase Dashboard: https://supabase.com/dashboard')
          console.log('2. Click on "SQL Editor" in the left sidebar.')
          console.log('3. Run this command:\n')
          console.log('ALTER TABLE public.emails ADD COLUMN IF NOT EXISTS background_name TEXT;\n')
        } else {
          console.error('\n❌ Could not find table "emails" in your Supabase database!')
          console.error('Error Code:', readError.code)
          console.error('Message:', readError.message)
          console.log('\n👉 TO FIX THIS:')
          console.log('1. Go to your Supabase Dashboard: https://supabase.com/dashboard')
          console.log('2. Click on "SQL Editor" in the left sidebar.')
          console.log('3. Click "+ New Query", paste the SQL below and click "Run":\n')
          console.log(`CREATE TABLE IF NOT EXISTS public.emails (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL,
  email_frequency INT DEFAULT 1,
  background_name TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.emails ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Allow service_role full access" ON public.emails
  FOR ALL USING (true) WITH CHECK (true);
`)
        }
        process.exitCode = 1
        return
      }

      console.log(`✓ Successfully reached Supabase! Found ${existingRows.length} existing record(s).`)

      console.log('\nStep 2: Testing row insertion with background_name into "emails" table...')
      const testEmail = `test.gujarat.${Date.now()}@example.com`

      const { data: insertedData, error: insertError } = await supabase
        .from('emails')
        .insert({
          email: testEmail,
          email_frequency: 1,
          background_name: 'Statue of Unity, Kevadia'
        })
        .select()

      if (insertError) {
        console.error('\n❌ Insert test failed!')
        console.error('Error:', insertError.message)
        process.exitCode = 1
        return
      }

      console.log('✓ Successfully inserted test visitor record!')
      console.log('  Stored record:', insertedData[0])

      console.log('\nStep 3: Cleaning up test record...')
      await supabase
        .from('emails')
        .delete()
        .eq('email', testEmail)

      console.log('✓ Cleaned up test record cleanly.')

      console.log('\n=============================================')
      console.log('🎉 SUPABASE IS FULLY CONNECTED & WORKING!')
      console.log('=============================================\n')
    } catch (err) {
      console.error('\n❌ Unexpected error:', err.message)
      process.exitCode = 1
    }
  }

  runTest()
}
